from __future__ import annotations

import base64
import json
import os
import shutil
import uuid
from pathlib import Path
from typing import Any, Dict, List, Optional, Union
from urllib.parse import quote

import requests

DEFAULT_HOST = "http://localhost:11434"
MAX_LASTK = 100


class OllamaBackend:
    def __init__(self, session: requests.Session, timeout: float) -> None:
        self.host = os.getenv("OLLAMA_HOST", DEFAULT_HOST).rstrip("/")
        if "://" not in self.host:
            self.host = f"http://{self.host}"
        self.session = session
        self.timeout = timeout
        self.history_dir = Path.home() / ".llmproxy" / "sessions"
        self.media_dir = Path.home() / ".llmproxy" / "media"

    def _request(self, method: str, path: str, payload: Optional[Dict] = None) -> Dict:
        try:
            resp = self.session.request(method, f"{self.host}{path}", json=payload, timeout=self.timeout)
        except requests.exceptions.RequestException as e:
            return {"error": f"Could not reach Ollama at {self.host}. Is it running? ({e})", "status_code": None}

        try:
            body = resp.json()
        except ValueError:
            body = {"error": resp.text}

        if not 200 <= resp.status_code < 300:
            return {"error": f"HTTP {resp.status_code}: {body.get('error', resp.text)}", "status_code": resp.status_code}
        return body

    def _history_path(self, session_id: str) -> Path:
        return self.history_dir / f"{quote(session_id, safe='')}.json"

    def _load_history(self, session_id: str) -> List[Dict[str, str]]:
        path = self._history_path(session_id)
        if not path.exists():
            return []
        return json.loads(path.read_text())

    def _append_history(self, session_id: str, query: str, response: str) -> None:
        history = self._load_history(session_id)
        history.append({"query": query, "response": response})
        self.history_dir.mkdir(parents=True, exist_ok=True)
        self._history_path(session_id).write_text(json.dumps(history))

    def upload_media(self, file_path: Union[str, Path], content_type: str) -> Dict:
        if not content_type.startswith("image/"):
            return {"error": f"Unsupported media type: {content_type}. Only image/* is supported with backend='ollama'", "status_code": None}
        path = Path(file_path)
        if not path.exists():
            return {"error": f"File not found: {path}", "status_code": None}

        media_id = f"{uuid.uuid4().hex}{path.suffix.lower()}"
        self.media_dir.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(path, self.media_dir / media_id)
        return {"ok": True, "id": media_id, "type": content_type}

    def _load_images(self, media: List[Dict[str, str]]) -> Union[List[str], Dict]:
        images = []
        for idx, item in enumerate(media):
            if not item["type"].startswith("image/"):
                return {"error": f"Unsupported media type at index {idx}: {item['type']}. Only image/* is supported with backend='ollama'", "status_code": None}
            # ids are generated by upload_media; reject anything that could escape media_dir
            path = self.media_dir / item["id"]
            if Path(item["id"]).name != item["id"] or not path.exists():
                return {"error": f"Unknown media id at index {idx}: {item['id']}. Upload it with upload_media first.", "status_code": None}
            images.append(base64.b64encode(path.read_bytes()).decode("ascii"))
        return images

    def clear_session(self, session_id: str) -> Dict:
        self._history_path(session_id).unlink(missing_ok=True)
        return {"result": f"Cleared local history for session {session_id}"}

    def generate(
        self,
        model: str,
        system: str,
        query: str,
        session_id: str,
        lastk: Optional[int],
        temperature: Optional[float],
        output_schema: Optional[Dict[str, Any]],
        media: Optional[List[Dict[str, str]]] = None,
    ) -> Dict:
        k = max(0, min(int(lastk or 0), MAX_LASTK))
        turns = self._load_history(session_id)[-k:] if k else []

        messages = [{"role": "system", "content": system}]
        for turn in turns:
            messages.append({"role": "user", "content": turn["query"]})
            messages.append({"role": "assistant", "content": turn["response"]})

        user_message: Dict[str, Any] = {"role": "user", "content": query}
        if media:
            images = self._load_images(media)
            if isinstance(images, dict):
                return images
            user_message["images"] = images
        messages.append(user_message)

        payload: Dict[str, Any] = {"model": model, "messages": messages, "stream": False}
        if temperature is not None:
            payload["options"] = {"temperature": temperature}
        if output_schema is not None:
            payload["format"] = output_schema

        res = self._request("POST", "/api/chat", payload)
        if "error" in res:
            return res

        text = res.get("message", {}).get("content", "")
        self._append_history(session_id, query, text)
        return {"result": text, "model": res.get("model", model), "status_code": 200}

    def model_info(self) -> Dict:
        res = self._request("GET", "/api/tags")
        if "error" in res:
            return res
        names = [m["name"] for m in res.get("models", [])]
        if not names:
            return {"result": "No local Ollama models found. Pull one with: ollama pull llama3.2"}
        return {"result": "The list of locally available Ollama models are: {}".format("\n".join(names))}
